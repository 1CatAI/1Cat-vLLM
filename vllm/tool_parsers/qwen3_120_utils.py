class UnexpectedAstError(Exception):
    """Raised when the AST structure does not match the expected
    pythonic tool call format."""

    pass


_JSON_NAME_LITERALS = {
    "null": None,
    "true": True,
    "false": False,
}


def get_parameter_value(val: ast.expr) -> Any:
    """Extract a Python literal value from an AST expression node.

    Handles constants, dicts, lists, and JSON-style name literals
    (null, true, false) that some models produce instead of Python
    literals (None, True, False).

    Raises:
        UnexpectedAstError: If the AST node is not a supported literal type.
    """
    if isinstance(val, ast.Constant):
        return val.value
    elif isinstance(val, ast.Dict):
        if not all(isinstance(k, ast.Constant) for k in val.keys):
            logger.warning(
                "Dict argument keys are not all literals: %s",
                ast.dump(val),
            )
            raise UnexpectedAstError("Dict tool call arguments must have literal keys")
        return {
            k.value: get_parameter_value(v)  # type: ignore
            for k, v in zip(val.keys, val.values)
        }
    elif isinstance(val, ast.List):
        return [get_parameter_value(v) for v in val.elts]
    elif isinstance(val, ast.Name) and val.id in _JSON_NAME_LITERALS:
        return _JSON_NAME_LITERALS[val.id]
    else:
        logger.warning(
            "Unsupported AST node type in tool call arguments: %s",
            ast.dump(val),
        )
        raise UnexpectedAstError("Tool call arguments must be literals")


def _ast_callable_dotted_name(node: ast.expr) -> str:
    """Return the dotted name for a call target, walking ``ast.Attribute``
    chains so ``a.b.c(...)`` becomes ``"a.b.c"``.

    Raises:
        UnexpectedAstError: If the chain does not bottom out in an
            ``ast.Name`` (e.g. subscript or call expression as receiver).
    """
    parts: list[str] = []
    current: ast.expr = node
    while isinstance(current, ast.Attribute):
        parts.append(current.attr)
        current = current.value
    if not isinstance(current, ast.Name):
        raise UnexpectedAstError("Invalid tool call name")
    parts.append(current.id)
    return ".".join(reversed(parts))


def handle_single_tool(call: ast.Call) -> ToolCall:
    """Convert a single AST function call node into a ToolCall object.

    Accepts both bare names (``foo(...)``) and dotted attribute chains
    (``a.b.c(...)``); the resulting tool call ``name`` field preserves the
    dotted form.

    Raises:
        UnexpectedAstError: If the call target is neither a simple name
            nor a chain of attribute accesses bottoming out in a name.
    """
    if not isinstance(call.func, (ast.Name, ast.Attribute)):
        logger.warning(
            "Tool call has non-simple function name: %s",
            ast.dump(call.func),
        )
        raise UnexpectedAstError("Invalid tool call name")
    function_name = _ast_callable_dotted_name(call.func)
    arguments = {}
    for keyword in call.keywords:
        arguments[keyword.arg] = get_parameter_value(keyword.value)
    return ToolCall(
        type="function",
        function=FunctionCall(
            name=function_name,
            arguments=json.dumps(arguments, ensure_ascii=False),
        ),
    )


def make_valid_python(text: str) -> tuple[str, str] | None:
    """Attempt to close all open brackets/quotes to make partial Python valid.

    Used during streaming to parse incomplete tool call expressions by
    appending the necessary closing characters.

    Returns:
        A tuple of (completed_text, added_suffix) if the text can be
        made valid, or None if the text is too incomplete to complete
        meaningfully (e.g. mid-parameter-name or mid-dict-key).

    Raises:
        UnexpectedAstError: If mismatched brackets or parentheses
            are detected.
    """
    bracket_stack: list[str] = []
    for index, char in enumerate(text):
        if char in {"[", "(", "{"}:
            bracket_stack.append(char)
        elif char == "]":
            if not bracket_stack or bracket_stack.pop() != "[":
                raise UnexpectedAstError("Mismatched square brackets")
        elif char == ")":
            if not bracket_stack or bracket_stack.pop() != "(":
                raise UnexpectedAstError("Mismatched parentheses")
        elif char == "}":
            if not bracket_stack or bracket_stack.pop() != "{":
                raise UnexpectedAstError("Mismatched curly braces")
        elif char in {"'", '"'}:
            if bracket_stack and bracket_stack[-1] == char:
                if index > 0 and text[index - 1] == "\\":
                    pass
                else:
                    bracket_stack.pop()
            elif bracket_stack and bracket_stack[-1] in {"'", '"'}:
                pass
            else:
                bracket_stack.append(char)

    text = text.rstrip()
    if text.endswith("=") or text.endswith(":"):
        return None
    if bracket_stack and bracket_stack[-1] == "{":
        trailing_dict_text = text[: text.rfind("{")]
        num_keys = trailing_dict_text.count(":")
        num_values = trailing_dict_text.count(",")
        if num_keys <= num_values:
            return None
    if bracket_stack and bracket_stack[-1] == "(":
        trailing_params_text = text[: text.rfind("(")]
        num_full_param_names = trailing_params_text.count("=")
        num_full_param_values = trailing_params_text.count(",")
        if num_full_param_names <= num_full_param_values:
            return None
    if text.endswith(","):
        text = text[:-1]
    if (
        bracket_stack
        and bracket_stack[-1] == "["
        and not text.endswith("[")
        and not text.endswith(")")
    ):
        return None

    _CLOSING = {"[": "]", "(": ")", "{": "}", "'": "'", '"': '"'}
    added_text = ""
    for char in reversed(bracket_stack):
        added_text += _CLOSING[char]

    candidate = text + added_text

    # Streaming partial text can land in shapes the bracket-counting
    # heuristics above don't catch. Two failure modes:
    #   1. Mid-key inside a dict (`..., "k`) closes to `..., "k"}` — a
    #      syntactically invalid mixed dict/set.
    #   2. A bare string inside a dict (`{"k`) closes to `{"k"}` — valid
    #      Python but a *set* literal, which downstream tool-call AST
    #      handling rejects.
    # Validate the candidate parses, has a body, and contains no Set
    # nodes (pythonic tool calls always use dicts for `{...}`).
    try:
        module = ast.parse(candidate)
    except SyntaxError:
        return None
    if not module.body:
        return None
    for node in ast.walk(module):
        if isinstance(node, ast.Set):
            return None

    return candidate, added_text


def extract_types_from_schema(schema: Any) -> list[str]:
    """Extract all possible type strings from a JSON Schema definition.

    Handles ``type`` (string or list), ``enum`` value inference, and
    recursive ``anyOf``/``oneOf``/``allOf``.  Returns ``["string"]``
    when no type information can be determined.
    """
    if schema is None or not isinstance(schema, dict):
        return ["string"]

    types: set[str] = set()

    if "type" in schema:
        type_value = schema["type"]
        if isinstance(type_value, str):
            types.add(type_value)
        elif isinstance(type_value, list):
            for t in type_value:
                if isinstance(t, str):
                    types.add(t)

    if "enum" in schema and isinstance(schema["enum"], list) and schema["enum"]:
        for value in schema["enum"]:
            if value is None:
                types.add("null")
            elif isinstance(value, bool):
                types.add("boolean")
            elif isinstance(value, int):
                types.add("integer")
            elif isinstance(value, float):
                types.add("number")
            elif isinstance(value, str):
                types.add("string")
            elif isinstance(value, list):
                types.add("array")
            elif isinstance(value, dict):
                types.add("object")

    for choice_field in ("anyOf", "oneOf", "allOf"):
        if choice_field in schema and isinstance(schema[choice_field], list):
            for choice in schema[choice_field]:
                types.update(extract_types_from_schema(choice))

    return list(types) if types else ["string"]


_TYPE_ALIASES: dict[str, str] = {
    "str": "string",
    "text": "string",
    "varchar": "string",
    "char": "string",
    "enum": "string",
    "int": "integer",
    "int32": "integer",
    "int64": "integer",
    "uint": "integer",
    "uint32": "integer",
    "uint64": "integer",
    "long": "integer",
    "short": "integer",
    "unsigned": "integer",
    "float": "number",
    "float32": "number",
    "float64": "number",
    "double": "number",
    "bool": "boolean",
    "dict": "object",
    "arr": "array",
    "list": "array",
    "sequence": "array",
}


def coerce_to_schema_type(value: str, schema_type: str | list[str]) -> Any:
    """Best-effort coercion of a raw string value to a JSON Schema type.

    Tries each type in priority order (null > integer > number > boolean >
    object > array > string) and returns the first successful coercion.
    Falls back to the original string when no coercion succeeds.

    Args:
        value: The raw string value from the model output.
        schema_type: One or more JSON Schema type strings
            (e.g. ``"string"`` or ``["string", "null"]``).
    """
    if isinstance(schema_type, str):
        schema_type = [schema_type]

    normalized_types = {
        _TYPE_ALIASES.get(key, key) for t in schema_type for key in [t.strip().lower()]
    }

    # Priority: null > integer > number > boolean > object > array > string
    type_priority = [
        "null",
        "integer",
        "number",
        "boolean",
        "object",
        "array",
        "string",
    ]

    for candidate_type in type_priority:
        if candidate_type not in normalized_types:
            continue

        if candidate_type == "null":
            if value.lower() == "null":
                return None
            continue
        if candidate_type == "string":
            return value
        if candidate_type == "integer":
            try:
                return int(value)
            except (ValueError, TypeError):
                continue
        if candidate_type == "number":
            try:
                val = float(value)
                return val if val != int(val) else int(val)
            except (ValueError, TypeError):
                continue
        if candidate_type == "boolean":
            lower_val = value.lower().strip()
            if lower_val in ("true", "1"):
                return True
            if lower_val in ("false", "0"):
                return False
            continue
        if candidate_type in ("object", "array"):
            try:
                return json.loads(value)
            except (json.JSONDecodeError, ValueError, TypeError):
                continue

    try:
        return json.loads(value)
    except (json.JSONDecodeError, ValueError):
        return value


def compute_tool_delta(
    previously_sent_args: str,
    new_call: ToolCall,
    index: int,
    withheld_suffix: str,
) -> DeltaToolCall | None:
    """Compute the incremental delta between previously streamed arguments
    and the current tool call state.

    Returns:
        A DeltaToolCall with only the new argument characters, or None
        if there is no difference from what was previously sent.
    """
    new_call_args = new_call.function.arguments
    if withheld_suffix:
        if not new_call_args.endswith(withheld_suffix):
            msg = (
                f"Tool call arguments '{new_call_args}' do not end with "
                f"expected withheld suffix '{withheld_suffix}'"
            )
            logger.error(msg)
            raise ValueError(msg)
        new_call_args = new_call_args[: -len(withheld_suffix)]
    if not previously_sent_args:
        return DeltaToolCall(
            id=new_call.id,
            type="function",
            index=index,
            function=DeltaFunctionCall(
                name=new_call.function.name,
                arguments=new_call_args,
            ),
        )

    arg_diff = new_call_args[len(previously_sent_args) :]
    return (
        DeltaToolCall(
            id=None,
            index=index,
            function=DeltaFunctionCall(arguments=arg_diff),
        )
        if arg_diff
        else None
    )


import re as _re

# opt22d(R1): 形似工具调用的标签匹配。
# 后缀分支 \"<[^<>]*$\" 覆盖“无右尖括号的截断残片”。
TOOL_LIKE_TAG_RE = _re.compile(
    r"</?(?:tool_call|toolcall|tool|function|parameter|param)\b[^<>]*?/?>"
    r"|</?(?:tool_call|toolcall|tool|function|parameter|param)\b[^<>]*$"
)


def escape_tool_like_tags(text: str) -> str:
    """opt22d(R1): 把“形似工具调用”的裸标签换成显示安全的形式，使下游无法把它们当真实调用执行。

    转义形如 `<function=Write>` -> `⟨'function=Write'⟩`（数学尖括号 + 成对单引号）。
    不用 `&lt;`/`&gt;` 实体的原因：① 纯文本渲染下很难看；② 若下游做 HTML 解码
    会被还原成 `<` 而失效。不用全角 `＜＞` 的原因：NFKC 会映射回 ASCII `<`/`>`。

    仅命中工具调用词族的标签名——`a<b`、`20<3`、`<p>` 等普通文本不受影响。
    **幂等**：已转义的 `⟨'...'⟩` 不再匹配（正则要求标签名紧跟 `<`），
    故对“已由工具解析器转义过”的内容重复施加也无害。
    """
    if not text:
        return text
    return TOOL_LIKE_TAG_RE.sub(
        lambda m: m.group(0).replace("<", "⟨'").replace(">", "'⟩"), text
    )


# [example 区间 2026-10-18] `example` 容器（`etool_call` = example tool call）。
# 区间内是模型**展示给用户**的示例，必须原样呈现（用户会复制粘贴），
# 既不转义、也不得被下游当成真实调用。未闭合区间延伸到文本末尾。
EXAMPLE_SPAN_RE = _re.compile(
    r"<example>.*?</example>|<etool_call>.*?</etool_call>"
    r"|<example>.*$|<etool_call>.*$",
    _re.S,
)


# markdown 代码围栏的**行首**标记（``` 或 ~~~，允许缩进）。
_FENCE_LINE_RE = _re.compile(r"(?m)^[ \t]*(?:`{3,}|~{3,})[^\n]*")


def _verbatim_spans(text: str) -> list[tuple[int, int]]:
    """示例区间：`<example>`/`<etool_call>` 块 + markdown 代码块，按位置合并。

    未闭合的一律延伸到文本末尾（此处是**展示收口**，内容已完整，不需延迟）。
    """
    raw: list[tuple[int, int]] = [
        (m.start(), m.end()) for m in EXAMPLE_SPAN_RE.finditer(text)
    ]
    marks = [(m.start(), m.end()) for m in _FENCE_LINE_RE.finditer(text)]
    for i in range(0, len(marks) - 1, 2):
        raw.append((marks[i][0], marks[i + 1][1]))
    if len(marks) % 2:
        raw.append((marks[-1][0], len(text)))
    raw.sort()
    merged: list[tuple[int, int]] = []
    for s, e in raw:
        if merged and s <= merged[-1][1]:
            merged[-1] = (merged[-1][0], max(merged[-1][1], e))
        else:
            merged.append((s, e))
    return merged


def escape_tool_like_tags_outside_examples(text: str) -> str:
    """对示例区间**之外**的形似工具标签做展示转义。

    serving 层统一收口用：示例区间内的裸标签是**示例正文**，必须原样下发；
    区间外仍按原规则转义（防止下游 harness 把文档里的标签当真实调用执行）。

    示例区间 = `<example>` / `<etool_call>` **以及 markdown 代码块**（2026-10-19）：
    代码块是模型展示工具调用写法的标准容器，块内标签属于示例而非可执行调用。
    """
    if not text:
        return text
    if (
        "<example" not in text
        and "<etool_call" not in text
        and "```" not in text
        and "~~~" not in text
    ):
        return escape_tool_like_tags(text)
    out: list[str] = []
    last = 0
    for start, end in _verbatim_spans(text):
        out.append(escape_tool_like_tags(text[last:start]))
        out.append(text[start:end])
        last = end
    out.append(escape_tool_like_tags(text[last:]))
    return "".join(out)


# opt22d（L-E）：工具类标签名（含别名），用于判断“残缺前缀”是否还可能是工具标签
_TOOL_TAG_NAMES = ("tool_call", "toolcall", "tool", "function", "parameter", "param")


def split_incomplete_tool_tag_tail(text: str) -> tuple[str, str]:
    """opt22d（L-E）：把末尾“尚未闭合、仍可能长成工具类标签”的片段摘出来。

    流式下标签会被切分（如 ``<p`` + ``arameter=file_path>``、``</function`` + ``>``）。
    若在**片段粒度**上做转义，两种失败模式：
      ① 标签名不完整（``<p``）→ 转义正则两个分支都不匹配 → **裸 ``<`` 泄漏**；
      ② 名完整而缺 ``>``（``</function``）→ 只替换 ``<`` → 后到的 ``>`` 不匹配
         → 产出 ``⟨'/function>`` 这类**畸形**（开一半、闭一半）。
    故调用方应把这种尾部**暂存**到下一轮，等 ``>`` 到齐后整体转义。

    Args:
        text: 待处理的文本（通常是累积缓冲/整段文本）

    Returns:
        ``(可安全转义的部分, 需暂存的尾部)``；无此类尾部时返回 ``(text, "")``。
    """
    i = text.rfind("<")
    if i == -1:
        return text, ""
    tail = text[i:]
    if ">" in tail:
        return text, ""
    # 仅 "<" / "</"（其后还没有任何字符）才可能长成任意工具标签：暂存一个字符宽度，
    # 下一字符到达即重新判定（自限，不会长期扣留）。
    if tail in ("<", "</"):
        return text[:i], tail
    inner = tail[1:]
    if inner.startswith("/"):
        inner = inner[1:]
    tok = ""
    for ch in inner:
        if ch.isalnum() or ch == "_":
            tok += ch
        else:
            break
    # opt22d 修正（2026-09-17）：tok 必须**非空**才算候选。空 tok 意味着 "<" 后紧跟
    # 空格/标点（正文里的 `a < b`、`tokenCount < limit`），永远长不成标签；旧写法
    # `name.startswith("")` 恒真 ⇒ 这类孤立 "<" 被当成候选暂存，其后全部文本被扣在
    # 缓冲里，流式结束不补发 ⇒ **消息在孤立 "<" 处被截断**（xml/coder 双路径实测复现）。
    if tok and any(name.startswith(tok) for name in _TOOL_TAG_NAMES):
        return text[:i], tail
    return text, ""


def mask_tool_like_tags_holding_tail(text: str) -> str:
    """opt22d（L-E）：转义的同时**丢弃**末尾未闭合的工具类标签片段。

    供 coder 使用——它靠“当前文本 − 上一轮文本”相减推导增量，
    必须保证遮罩结果的前缀关系稳定，故暂存片段不能出现在遮罩输出里，
    留待下一轮片段闭合后以整体转义的形式出现。
    """
    head, _held = split_incomplete_tool_tag_tail(text)
    return escape_tool_like_tags(head)


