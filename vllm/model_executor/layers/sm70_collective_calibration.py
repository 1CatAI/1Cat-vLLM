"""GPU classification of FP32 addition trees for explicit SM70 row plans."""

from vllm.triton_utils import tl, triton


@triton.jit
def update_mask(
    reference,
    masks,
    expected,
    N: tl.constexpr,
    OFFSET: tl.constexpr,
    BLOCK: tl.constexpr,
):
    i = tl.program_id(0) * BLOCK + tl.arange(0, BLOCK)
    bits = tl.load(reference + OFFSET + i, i < N, other=0).to(tl.uint32, bitcast=True)
    mask = tl.load(masks + i, i < N, other=0).to(tl.uint32)
    for tree in tl.static_range(15):
        correct = bits == tl.load(expected + tree)
        mask = mask & tl.where(correct, 0x7FFF, 0x7FFF ^ (1 << tree)).to(tl.uint32)
    tl.store(masks + i, mask.to(tl.int16), i < N)


@triton.jit
def decode_mask(masks, codes, stats, N: tl.constexpr, BLOCK: tl.constexpr):
    i = tl.program_id(0) * BLOCK + tl.arange(0, BLOCK)
    mask = tl.load(masks + i, i < N, other=0).to(tl.uint32)
    unique = (mask != 0) & ((mask & (mask - 1)) == 0)
    code = tl.full((BLOCK,), 255, tl.uint8)
    for tree in tl.static_range(15):
        code = tl.where(mask == (1 << tree), tree, code).to(tl.uint8)
    tl.store(codes + i, code, i < N)
    tl.atomic_add(stats, tl.sum(((i < N) & (mask == 0)).to(tl.int32)))
    tl.atomic_add(stats + 1, tl.sum(((i < N) & (mask != 0) & (~unique)).to(tl.int32)))


